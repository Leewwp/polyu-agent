- 允许标签：`<table> <thead> <tbody> <tr> <th> <td> <br>`；允许属性：`rowspan`、`colspan`、`align`。
- 禁止 `<script> <style> <iframe>`、任何 `on*` 事件属性、内联 JS 或样式表。

## 简单表格

